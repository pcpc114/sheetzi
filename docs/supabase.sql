-- ===========================================================================
--  시트지 — Supabase(Postgres) 저장소 만들기            (SPEC 29.3)
-- ===========================================================================
--
--  이 파일은 "한 번만" 실행하는 준비 작업입니다. 여기서 만드는 표(table) 3개가
--  없으면 서버는 켜지지 않고 "테이블이 없습니다" 라고 알려 줍니다. 그게 정상입니다.
--  (아무 표도 없는 데이터베이스에 서버가 그냥 켜지는 것이 제일 위험합니다.
--   화면은 멀쩡한데 적은 내용이 아무 데도 저장되지 않기 때문입니다.)
--
--  ── 붙여넣는 방법 (Postgres 를 한 번도 안 써 봤어도 괜찮습니다) ──────────────
--
--   1. supabase.com 에 로그인 → 사용할 프로젝트를 클릭합니다.
--   2. 왼쪽 메뉴에서 "SQL Editor" 를 클릭합니다. (아이콘이 종이+연필 모양입니다)
--   3. 오른쪽 위 "New query" 를 누릅니다. 빈 칸이 하나 나옵니다.
--   4. 이 파일의 내용을 처음부터 끝까지 전부 복사해서 그 빈 칸에 붙여넣습니다.
--      (일부만 붙여넣지 마세요. 전부 한 번에 넣으면 됩니다.)
--   5. 오른쪽 아래 "Run" 버튼을 누릅니다. (단축키: Ctrl+Enter, 맥은 Cmd+Enter)
--
--  ── 무엇이 보이면 성공인가 ────────────────────────────────────────────────
--
--   화면 아래에 초록색으로  Success. No rows returned  라고 나오면 끝입니다.
--   "표가 안 보이는데요?" — 원래 이 명령은 결과 표를 만들지 않습니다.
--   확인하고 싶으면 왼쪽 메뉴 "Table Editor" 에 들어가 보세요. 아래 세 이름이
--   보이면 제대로 만들어진 것입니다:  sz_documents / sz_journal / sz_backups
--   (맨 아래에 "확인용 조회" 도 준비해 두었습니다.)
--
--  ── 실수로 두 번 실행해도 되나요 ──────────────────────────────────────────
--
--   됩니다. 모든 명령에 "if not exists"(없을 때만 만들어라) 가 붙어 있어서,
--   이미 있는 것은 그대로 두고 넘어갑니다. 안에 든 자료도 지워지지 않습니다.
--
--  ── 다 실행한 다음 할 일 ─────────────────────────────────────────────────
--
--   서버에 값 두 개를 알려 줍니다.
--     SUPABASE_URL          = 프로젝트 주소 (https://….supabase.co)
--     SUPABASE_SERVICE_KEY  = Supabase 의 "비밀 키". 두 형식 중 아무거나 하나면 됩니다.
--         (가) 지금 방식 — Project Settings → API Keys → "Secret keys" 의
--              sb_secret_… 값. 점으로 가려져 있으니 눈 모양 아이콘으로 펼친 뒤
--              복사 버튼으로 복사하세요. (줄이 없으면 Create new secret key)
--         (나) 예전 방식 — 같은 화면의 "Legacy anon, service_role API keys" 탭에
--              있는 service_role 값 (eyJ… 로 시작하는 아주 긴 한 줄). 지금도 그대로
--              동작하지만 Supabase 가 2026년 말에 없앨 예정입니다.
--         어느 형식인지 알려 주는 설정은 없습니다. 서버가 값의 생김새를 보고
--         알아서 맞춥니다.
--         ⚠ "Publishable key"(sb_publishable_…) 와 예전 anon 키는 아닙니다.
--           공개용이라 아래에서 만드는 표 3개에는 권한이 하나도 없습니다(5번 참고).
--
--   넣는 곳은 둘 중 하나입니다.
--     (가) 내 컴퓨터나 내가 직접 운영하는 서버 → 프로젝트 폴더의 .env 파일
--          (.env.example 을 복사해서 만드세요). 서버는 시작할 때 이 폴더의 .env 를
--          읽습니다. 값을 바꾸면 서버를 껐다 켜야 반영됩니다.
--     (나) Render·Railway·Fly.io 처럼 대시보드가 있는 곳 → 그 대시보드의
--          Environment / Variables 화면. 파일을 만들 필요가 없습니다.
--   같은 이름이 양쪽에 다 있으면 환경변수(나)가 이기고 .env(가)는 무시됩니다.
--
--   제대로 들어갔는지 확인하는 법: 서버를 켠 직후 로그에 이 줄이 보이면 됩니다.
--     [시트지] 문서 저장소: Supabase (….supabase.co) — 문서가 데이터베이스에 저장됩니다.
--   대신 "문서 저장소: 파일 (data/ 디렉터리)" 가 보이면 SUPABASE_URL 이 서버에
--   전달되지 않은 것입니다. 그 상태로 쓰면 화면은 멀쩡한데 저장은 이 데이터베이스가
--   아니라 서버 디스크로 갑니다.
--
--   바로 다음 줄에는 어떤 키를 넣었는지 "형식"만 찍힙니다(값은 절대 안 찍힙니다).
--     [시트지] Supabase 키 형식: 새 형식 비밀 키 (sb_secret_) — apikey 헤더로만 보냅니다.
--   예전 service_role 키를 넣었다면 "레거시 JWT 키 (service_role)" 로 나오고, 헤더를
--   두 개 보낸다고 적힙니다. 둘 다 정상이고 고를 것도 없습니다 — 형식에 따라 보내는
--   방법이 달라서 서버가 알아서 맞추는 것뿐입니다. 여기에 "공개 키" 라는 말이 보이면
--   잘못된 키를 넣은 것이고, 서버는 그 자리에서 이유를 말하고 멈춥니다.
--
--   ⚠ 이 비밀 키는 이 데이터베이스 전체를 여는 열쇠입니다. 서버 쪽(.env 또는
--     대시보드 환경변수)에만 두세요. 브라우저·깃허브·채팅·스크린샷에 절대 넣지 마세요.
--     혹시 노출됐다면 Supabase 대시보드에서 즉시 새 키를 만들고(Create new secret key)
--     노출된 키를 Revoke 하세요. 예전 방식 키라면 같은 화면의 Reset 입니다.
--
--   SUPABASE_URL 을 비워 두면 서버는 예전처럼 data/ 폴더의 파일에 저장합니다.
--   어느 쪽을 쓸지는 오직 이 설정값으로만 정해집니다.
--
--  ── 기존 문서는 어떻게 되나요 ────────────────────────────────────────────
--
--   여기서 만든 표 3개는 "비어" 있습니다. 그렇다고 문서 목록까지 비어 보이지는
--   않습니다. 저장소가 텅 비어 있으면 서버가 견본 문서를 하나 만들어 넣기 때문에,
--   Supabase 로 바꾸고 서버를 켜면 목록에 "시작 시트" 라는 문서가 하나 보입니다.
--   그게 정상입니다. 로그에도 이렇게 찍힙니다:
--
--     [시트지] 시작 문서를 만들었습니다: 시작 시트 (start1)
--
--   이 문서는 data/ 에서 넘어온 것이 아니라 방금 만들어진 예시입니다. 문서 번호가
--   data/start1.json 과 똑같은 start1 이라 헷갈리기 쉬운데, 서로 아무 관계도 없습니다.
--   지워도 data/ 폴더의 파일에는 아무 일도 일어나지 않습니다.
--
--   data/ 폴더의 기존 문서를 이 데이터베이스로 옮겨 주는 도구는 없습니다.
--   그리고 data/ 폴더는 읽지도, 고치지도, 지우지도 않습니다. 파일은 그대로 있고,
--   SUPABASE_URL 을 다시 비우면 예전 문서가 그대로 다시 보입니다.
--
--   내용을 옮기고 싶으면 예전 문서와 새 문서를 각각 탭으로 열어 두고
--   Ctrl+A → Ctrl+C → Ctrl+V 로 직접 복사하면 됩니다. 자세한 순서와, 그때
--   따라오는 것과 안 따라오는 것은 README 에 적어 두었습니다.
--
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- 1. 문서 본체 — sz_documents
-- ---------------------------------------------------------------------------
-- 문서 한 개당 한 줄입니다. 파일 방식의 data/<문서id>.json 과 같은 역할입니다.
--   id         문서 번호(영문 소문자+숫자). 중복될 수 없는 대표값(primary key)입니다.
--   doc        문서 내용 전체. jsonb 는 "JSON 을 그대로 담는 칸" 이라고 보면 됩니다.
--   rev        이 내용이 몇 번째 수정본인지 나타내는 숫자.
--   updated_at 마지막으로 저장한 시각(1970년부터의 밀리초).
create table if not exists public.sz_documents (
  id          text primary key,
  doc         jsonb  not null,
  rev         bigint,
  updated_at  bigint
);

-- ---------------------------------------------------------------------------
-- 2. 저널(작업 기록) — sz_journal
-- ---------------------------------------------------------------------------
-- 누가 무엇을 고쳤는지 한 줄씩 계속 쌓기만 하는 표입니다. 파일 방식의
-- data/<문서id>.log 와 같은 역할이고, 시트지가 "입력한 것은 잃어버리지 않는다"고
-- 약속할 수 있는 이유입니다. 서버는 이 줄이 데이터베이스에 확실히 들어간 것을
-- 확인한 뒤에야 브라우저에 "저장됨" 이라고 알려 줍니다.
--
--   seq      1, 2, 3 … 자동으로 붙는 번호(bigserial). 기록된 순서 그 자체입니다.
--   doc_id   어느 문서의 기록인지.
--   rec      기록 내용(JSON).
--   at       기록된 시각(밀리초).
--
-- 문서를 저장(압축)할 때마다, 그 저장본에 이미 들어간 번호까지만 지워집니다.
-- 저장하는 도중에 새로 들어온 기록은 번호가 더 크므로 지워지지 않고 살아남습니다.
-- 줄 수가 늘 적게 유지되는 것이 정상입니다.
create table if not exists public.sz_journal (
  seq     bigserial primary key,
  doc_id  text   not null,
  rec     jsonb  not null,
  at      bigint
);

-- ---------------------------------------------------------------------------
-- 3. 백업 — sz_backups
-- ---------------------------------------------------------------------------
-- 저장할 때마다 그때의 문서를 한 벌씩 남겨 둡니다. 파일 방식의
-- <문서id>.bak.1 … .bak.5 와 같은 역할이고, 문서당 최근 5개만 남고 오래된 것은
-- 서버가 알아서 지웁니다. 실수로 크게 지워 버렸을 때 되돌릴 수 있는 보험입니다.
create table if not exists public.sz_backups (
  seq     bigserial primary key,
  doc_id  text   not null,
  doc     jsonb  not null,
  at      bigint
);


-- ---------------------------------------------------------------------------
-- 4. 색인(index) — 찾는 속도를 위한 것
-- ---------------------------------------------------------------------------
-- 색인은 책 뒤의 "찾아보기" 와 같습니다. 없어도 동작은 하지만, 줄이 많아지면
-- 데이터베이스가 표를 처음부터 끝까지 훑게 되어 점점 느려집니다.
--
-- 저널은 언제나 "이 문서의 기록을, 번호 순서대로" 읽고 지웁니다. 그래서
-- (doc_id, seq) 두 칸을 묶어서 색인합니다.
create index if not exists sz_journal_doc_seq_idx
  on public.sz_journal (doc_id, seq);

-- 백업은 언제나 "이 문서의 백업을, 최신부터" 읽습니다. 그래서 번호를 거꾸로
-- (desc) 색인합니다.
create index if not exists sz_backups_doc_seq_idx
  on public.sz_backups (doc_id, seq desc);


-- ---------------------------------------------------------------------------
-- 5. 잠그기 — RLS (Row Level Security, 줄 단위 보안)
-- ---------------------------------------------------------------------------
-- 여기가 보안에서 제일 중요한 부분입니다.
--
-- Supabase 프로젝트에는 열쇠가 두 종류 있습니다. 최근에 이름이 바뀌어서 화면에
-- 옛 이름과 새 이름이 같이 보일 수 있는데, 하는 일은 예전 그대로입니다.
--   · 공개용 열쇠 — 새 이름 Publishable key (sb_publishable_…), 옛 이름 anon.
--                   브라우저에 노출되어도 괜찮다고 여겨지는 열쇠입니다.
--   · 비밀 열쇠   — 새 이름 Secret key (sb_secret_…), 옛 이름 service_role.
--                   전부 열 수 있어서 서버에만 둡니다. 시트지가 쓰는 쪽입니다.
--
-- 아래 명령은 세 표에 "RLS 를 켜고, 통과 규칙(policy)은 하나도 만들지 않는" 것입니다.
-- 규칙이 하나도 없으면 공개용 열쇠로는 읽기도 쓰기도 전부 막힙니다. 즉 누군가
-- 그 열쇠를 알아내도 이 표들에서는 아무것도 할 수 없습니다.
--
-- 반대로 비밀 열쇠는 원래 RLS 를 통과하도록 만들어진 특별한 열쇠라 서버는 지금처럼
-- 잘 동작합니다. "규칙이 없는데 서버는 왜 되지?" 의 답이 이것입니다. (새 이름이든
-- 옛 이름이든 데이터베이스 안에서는 같은 역할로 연결됩니다. 공개용 열쇠는 아래
-- revoke 에 적힌 anon 역할로, 비밀 열쇠는 RLS 를 통과하는 service_role 역할로요.)
--
-- ⚠ Supabase 대시보드에 "이 표에 정책이 없습니다" 같은 경고가 떠도 정상입니다.
--    일부러 그렇게 만든 것이니 정책을 추가하지 마세요.
alter table public.sz_documents enable row level security;
alter table public.sz_journal   enable row level security;
alter table public.sz_backups   enable row level security;

-- 한 겹 더 잠급니다. 위의 RLS 만으로도 충분하지만, 공개용 역할들에게 준 기본
-- 권한까지 회수해 두면 설정이 잘못되어도 열리지 않습니다. (자물쇠 두 개)
revoke all on table public.sz_documents from anon, authenticated;
revoke all on table public.sz_journal   from anon, authenticated;
revoke all on table public.sz_backups   from anon, authenticated;


-- ===========================================================================
--  확인용 조회 — 아래 한 줄만 따로 선택해서 Run 하면 결과 표가 나옵니다.
--  세 줄(sz_backups / sz_documents / sz_journal)이 보이고 rls_enabled 가 모두
--  true 이면 준비가 끝난 것입니다.
-- ===========================================================================
--
--   select tablename, rowsecurity as rls_enabled
--     from pg_tables
--    where schemaname = 'public'
--      and tablename in ('sz_documents', 'sz_journal', 'sz_backups')
--    order by tablename;
--
--
--  참고 1) public 이 아닌 다른 스키마에 만들고 싶다면, 이 파일의 public 을 전부
--          그 이름으로 바꾸고 SUPABASE_SCHEMA=그이름 을 .env(또는 대시보드
--          환경변수)에 넣으세요.
--          그리고 대시보드의 Project Settings → Data API → Exposed schemas 에도
--          그 이름을 추가해야 합니다. 특별한 이유가 없으면 public 그대로 두세요.
--
--  참고 2) 전부 지우고 처음부터 다시 하고 싶을 때 쓰는 명령입니다. 문서와 기록이
--          "영구히" 사라지므로, 정말 그럴 때만 앞의 -- 를 지우고 실행하세요.
--
--   -- drop table if exists public.sz_journal;
--   -- drop table if exists public.sz_backups;
--   -- drop table if exists public.sz_documents;
